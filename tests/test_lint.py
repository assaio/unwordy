import pytest

from unwordy import extract, lint

from conftest import FIXTURES

RULES = ["H1", "H2", "H3", "H4", "S1", "S2", "S3", "S4", "S5", "S6", "S7"]
QUESTION = "Is the retry limit configurable?"


def fixture_path(kind, rule):
    matches = sorted((FIXTURES / kind).glob(f"{rule}.*"))
    assert len(matches) == 1, f"one {kind} fixture per rule, found {matches}"
    return matches[0]


def lint_fixture(path, settings, root):
    surface = path.name.split(".")[1]
    text = path.read_text(encoding="utf-8")
    if surface == "code":
        target = root / ("sample" + path.suffix)
        change = extract.Change(str(target), text.splitlines(), set(range(len(text.splitlines()))))
        return lint.lint_change(change, settings, str(root))
    if surface == "reply":
        return lint.lint_reply(text, QUESTION, settings)
    title, _, body = text.partition("\n")
    message = extract.Message(surface, "test", title.strip(), body.strip())
    return lint.lint_message(message, settings)


@pytest.mark.parametrize("rule", RULES)
def test_slop_fixture_triggers_its_rule(rule, settings, project):
    findings = lint_fixture(fixture_path("slop", rule), settings, project)
    assert rule in [f.family for f in findings], findings


@pytest.mark.parametrize("rule", RULES)
def test_clean_fixture_is_silent(rule, settings, project):
    assert lint_fixture(fixture_path("clean", rule), settings, project) == []


@pytest.mark.parametrize("rule", RULES)
def test_reason_names_the_rule(rule, settings, project):
    findings = lint_fixture(fixture_path("slop", rule), settings, project)
    finding = next(f for f in findings if f.family == rule)
    assert str(finding).startswith(f"unwordy {finding.rule}: ")
    assert finding.rule[:2] == rule and len(finding.rule) <= 3
    assert "\n" not in str(finding)


def code_findings(project, name, source, settings, added=None):
    lines = source.splitlines()
    change = extract.Change(str(project / name), lines, added if added is not None else set(range(len(lines))))
    return [f.family for f in lint.lint_change(change, settings, str(project))]


def test_attribution_is_denied_in_code_and_prose(project, settings):
    assert "H1" in code_findings(project, "a.py", "# Generated with Claude Code\nx = 1\n", settings)
    assert "H1" in code_findings(project, "NOTES.md", "\U0001F916 Generated with Claude Code\n", settings)



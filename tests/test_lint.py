def test_per_surface_limits_override_the_flat_keys(settings):
    settings["pr.max_body_lines"], settings["commit.max_subject"] = 20, 60
    body = "line\n" * 15
    assert lint.lint_message(extract.Message("pr", "gh pr create", "Title", body), settings) == []
    assert [f.rule for f in lint.lint_message(extract.Message("commit", "git commit", "Title", body), settings)] == ["S5b"]
    subject = "x" * 65
    assert [f.rule for f in lint.lint_message(extract.Message("commit", "git commit", subject, ""), settings)] == ["S5a"]
    assert lint.lint_message(extract.Message("pr", "gh pr create", subject, ""), settings) == []


def test_repo_conventions_skip_subject_length_and_opener_for_commits(settings):
    body = "This commit adds retries.\n\n## Summary\n\nx\n\n## Test plan\n\ny\n"
    message = extract.Message("commit", "git commit", "x" * 80, body)
    assert [f.rule for f in lint.lint_message(message, settings)] == ["S5a", "S6a", "S6c"]
    assert [f.rule for f in lint.lint_message(message, settings, conventions=True)] == ["S6a"]
    pr = extract.Message("pr", "gh pr create", "x" * 80, body)
    assert [f.rule for f in lint.lint_message(pr, settings, conventions=True)] == ["S5a", "S6a", "S6c"]

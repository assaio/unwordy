def test_docstring_rule_skips_declarations_without_a_body(project, settings):
    interface = (
        "interface Repo {\n"
        "  /**\n   * Finds a user.\n   *\n   * Returns null when missing.\n   */\n"
        "  find(id: string): Promise<User | null>;\n"
        "}\n"
        "function later() {\n  return 1;\n}\n"
    )
    assert code_findings(project, "repo.ts", interface, settings) == []
    header = "/**\n * Checksum.\n *\n * CRC over the frame.\n */\nuint32_t checksum(const uint8_t *p, size_t n);\n"
    assert code_findings(project, "sum.h", header, settings) == []
    decorated = "/**\n * Input.\n *\n * Bound by the parent.\n */\n@Input()\nname = '';\n"
    assert code_findings(project, "c.ts", decorated, settings) == []
    real = "/**\n * Adds.\n *\n * Two numbers.\n */\nfunction add(a, b) {\n  return a + b;\n}\n"
    assert code_findings(project, "add.js", real, settings) == ["S4"]


